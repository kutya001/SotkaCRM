export const APP_VERSION: string = CHANGELOG[0].version;

/** Сравнение версий «1.10.0» > «1.9.0»: отрицательное — a старше b */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map((n) => Number(n) || 0);
  const pb = b.split('.').map((n) => Number(n) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d !== 0) return d;
  }
  return 0;
}

/** Записи новее последней просмотренной версии (без нее — только текущая) */
export function entriesSince(lastSeen: string | null | undefined): ChangelogEntry[] {
  if (!lastSeen) return CHANGELOG.slice(0, 1);
  return CHANGELOG.filter((e) => compareVersions(e.version, lastSeen) > 0);
}
