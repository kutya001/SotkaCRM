/** Справка для маршрута (по префиксу пути) */
export function getModuleHelp(pathname: string): ModuleHelp | null {
  if (pathname === '/') return HELP['/'];
  const key = Object.keys(HELP).find((k) => k !== '/' && pathname.startsWith(k));
  return key ? HELP[key] : null;
}
