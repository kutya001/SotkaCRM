export interface ScriptFillContext {
  /** Имя клиента из лида */
  clientName?: string | null;
  /** Имя сотрудника CRM */
  managerName?: string | null;
}

/**
 * Подстановка в текст скрипта: {имя} — имя клиента («Здравствуйте, {имя}!» без имени → «Здравствуйте!»,
 * «{имя}, подскажите» → «Подскажите»), {менеджер} — имя сотрудника (без имени — «[ваше имя]»).
 */
export function fillScript(text: string, ctx: ScriptFillContext = {}): string {
  const client = ctx.clientName?.trim();
  const manager = ctx.managerName?.trim() || '[ваше имя]';
  let out = text.replace(/\{менеджер\}/g, manager);
  if (client) {
    out = out.replace(/\{имя\}/g, client);
  } else {
    out = out
      .replace(/,\s*\{имя\}(?=[!?.])/g, '')
      .replace(/^\{имя\},\s*(\S)/u, (_m, first: string) => first.toUpperCase())
      .replace(/\{имя\},?\s*/g, '');
  }
  return out
    .split('\n')
    .map((line) => line.replace(/[ \t]{2,}/g, ' ').trimEnd())
    .join('\n')
    .trim();
}

/** Поля для ручного заполнения: [дата и время], [ТЦ / рынок] */
export function manualFieldsOf(text: string): string[] {
  return Array.from(text.matchAll(/\[([^\]]+)\]/g), (m) => m[1]);
}

/** Поиск по названию, тексту, разделу и тегам */
export function matchesScript(script: SalesScript, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return (
    script.title.toLowerCase().includes(q) ||
    script.text.toLowerCase().includes(q) ||
    script.category.toLowerCase().includes(q) ||
    script.tags.some((t) => t.toLowerCase().includes(q))
  );
}
