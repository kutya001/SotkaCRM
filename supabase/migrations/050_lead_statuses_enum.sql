-- Новые статусы лида (тип lead_status):
--  - «Нет ответа» — клиенту написали или позвонили, он молчит (рядом с «Открыт»);
--  - «Встреча» — записан на выезд специалиста или видеозвонок (после «Назначен»);
--  - «Перезвонить» — клиент думает, следующий контакт в назначенную дату.
-- Отдельная миграция: новое значение enum нельзя использовать в той же транзакции, где оно
-- добавлено. Выполните этот файл первым и отдельно, затем 051.
-- Миграция идемпотентна (ADD VALUE IF NOT EXISTS).
-- ==============================================================================

ALTER TYPE public.lead_status ADD VALUE IF NOT EXISTS 'Нет ответа' AFTER 'Открыт';
ALTER TYPE public.lead_status ADD VALUE IF NOT EXISTS 'Встреча' AFTER 'Назначен';
ALTER TYPE public.lead_status ADD VALUE IF NOT EXISTS 'Перезвонить' AFTER 'Встреча';

NOTIFY pgrst, 'reload schema';
